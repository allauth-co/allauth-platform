import * as z from "zod";

const reserved = new Set(["admin", "platform", "auth", "api", "allauth", "public", "internal"]);
export const projectSlug = z.string().regex(/^[a-z][a-z0-9-]{1,47}$/).refine((value) => !reserved.has(value), "Choose a different project identifier.");
export const projectOrigin = z.string().url().refine((value) => {
	const url = new URL(value);
	return value === url.origin && !url.username && !url.password && !value.includes("*") && (url.protocol === "https:" || (url.protocol === "http:" && ["localhost", "127.0.0.1", "[::1]"].includes(url.hostname)));
}, "Use an exact HTTPS app origin, or a loopback development origin.");
export const projectInput = z.object({ name: z.string().trim().min(2).max(100), slug: projectSlug, primaryOrigin: projectOrigin, origins: z.array(projectOrigin).max(10).default([]), applicationId: z.uuid().optional(), environment: z.enum(["development", "production"]).optional(), workspaceId: z.uuid().optional() }).strict().refine((value) => value.environment !== "production" || !value.primaryOrigin.startsWith("http:"), "Production environments require HTTPS.");
export type ProjectInput = z.infer<typeof projectInput>;

/** A schema identifier is generated by the server and never derived from an app's name. */
export function checkedProjectSchema(value: string): string {
	if (!/^allauth_project_[a-f0-9]{32}$/.test(value)) throw new Error("Invalid project storage namespace.");
	return value;
}
